        "// Факт 1: Драйвер подсистемы NeuralTower DMA использует кольцевой буфер `nt_ring_buffer`.\n"
        "// Указатель записи `write_ptr` обновляется БЕЗ атомарного барьера памяти (Memory Barrier) в функции `nt_push_tail`.\n"
